/**
 * §3.8 — the share of a turn's ceiling its supersedable results may hold verbatim before the
 * oldest the model has read collapse to their lines. A share rather than a count, because a count
 * of pages is either a few hundred tokens or a few hundred thousand depending on the pages, and
 * a count of two made every task needing three pages loop until its budget ran out.
 */
export const SUPERSEDABLE_RETENTION_SHARE = 0.3;

/** §3.8 — however low the ceiling, this many supersedable results stay verbatim before any collapses */
export const SUPERSEDABLE_RETENTION_FLOOR = 2;
